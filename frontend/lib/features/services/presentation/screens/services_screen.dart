import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:sanad/core/repositories/supabase_repository.dart';
import 'package:sanad/core/theme/app_colors.dart';
import 'package:sanad/features/services/data/models/service_model.dart';
import 'package:sanad/features/services/presentation/widgets/service_card.dart';

/// Screen that displays available community services.
class ServicesScreen extends ConsumerWidget {
  /// Creates a [ServicesScreen].
  const ServicesScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final servicesAsync = ref.watch(servicesProvider);

    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: _buildAppBar(context, ref),
      body: RefreshIndicator(
        onRefresh: () async => ref.refresh(servicesProvider.future),
        child: _buildBody(servicesAsync),
      ),
    );
  }

  /// Builds the application bar.
  PreferredSizeWidget _buildAppBar(BuildContext context, WidgetRef ref) {
    return AppBar(
      title: const Text('Community Services'),
      centerTitle: false,
      actions: [_buildOfferHelpButton(context, ref), const SizedBox(width: 8)],
    );
  }

  /// Builds the 'Offer Help' button.
  Widget _buildOfferHelpButton(BuildContext context, WidgetRef ref) {
    return TextButton.icon(
      onPressed: () => _showOfferHelpDialog(context, ref),
      icon: const Icon(Icons.volunteer_activism, size: 18),
      label: const Text('Offer Help'),
      style: TextButton.styleFrom(foregroundColor: AppColors.primary),
    );
  }

  void _showOfferHelpDialog(BuildContext context, WidgetRef ref) {
    final titleController = TextEditingController();
    final descriptionController = TextEditingController();
    final providerController = TextEditingController();
    final emailController = TextEditingController();
    String selectedCategory = 'other';
    final formKey = GlobalKey<FormState>();

    showDialog(
      context: context,
      builder: (context) => AlertDialog(
        title: const Text('Offer Help'),
        content: SingleChildScrollView(
          child: Form(
            key: formKey,
            child: Column(
              mainAxisSize: MainAxisSize.min,
              children: [
                TextFormField(
                  controller: titleController,
                  decoration: const InputDecoration(labelText: 'Service Title'),
                  validator: (value) =>
                      value?.isEmpty ?? true ? 'Required' : null,
                ),
                SizedBox(height: 8),
                TextFormField(
                  controller: descriptionController,
                  decoration: const InputDecoration(labelText: 'Description'),
                ),
                SizedBox(height: 8),
                DropdownButtonFormField<String>(
                  initialValue: selectedCategory,
                  decoration: const InputDecoration(labelText: 'Category'),
                  items:
                      [
                            'transportation',
                            'companion',
                            'home-help',
                            'medical',
                            'other',
                          ]
                          .map(
                            (c) => DropdownMenuItem(value: c, child: Text(c)),
                          )
                          .toList(),
                  onChanged: (value) => selectedCategory = value!,
                ),
                SizedBox(height: 8),
                TextFormField(
                  controller: providerController,
                  decoration: const InputDecoration(labelText: 'Your Name'),
                  validator: (value) =>
                      value?.isEmpty ?? true ? 'Required' : null,
                ),
                SizedBox(height: 8),
                TextFormField(
                  controller: emailController,
                  decoration: const InputDecoration(labelText: 'Contact Email'),
                  validator: (value) =>
                      value?.isEmpty ?? true ? 'Required' : null,
                ),
              ],
            ),
          ),
        ),
        actions: [
          TextButton(
            onPressed: () => Navigator.pop(context),
            child: const Text('Cancel'),
          ),
          ElevatedButton(
            onPressed: () async {
              if (formKey.currentState!.validate()) {
                try {
                  final newService = ServiceModel(
                    id: '', // Generated by DB
                    title: titleController.text,
                    description: descriptionController.text,
                    category: selectedCategory,
                    provider: providerController.text,
                    contactEmail: emailController.text,
                    rating: 0,
                    reviewsCount: 0,
                    isAvailable: true,
                  );

                  await ref
                      .read(supabaseRepositoryProvider)
                      .addService(newService);
                  ref.invalidate(servicesProvider); // Refresh list

                  if (context.mounted) {
                    Navigator.pop(context);
                    ScaffoldMessenger.of(context).showSnackBar(
                      const SnackBar(
                        content: Text('Service offered successfully!'),
                      ),
                    );
                  }
                } catch (e) {
                  if (context.mounted) {
                    ScaffoldMessenger.of(
                      context,
                    ).showSnackBar(SnackBar(content: Text('Error: $e')));
                  }
                }
              }
            },
            child: const Text('Submit'),
          ),
        ],
      ),
    );
  }

  /// Builds the body content based on data state.
  Widget _buildBody(AsyncValue<List<ServiceModel>> servicesAsync) {
    return servicesAsync.when(
      data: (services) => _buildServicesList(services),
      loading: () => const Center(child: CircularProgressIndicator()),
      error: (err, stack) => Center(child: Text('Error: $err')),
    );
  }

  /// Builds the list of services.
  Widget _buildServicesList(List<ServiceModel> services) {
    if (services.isEmpty) {
      return const Center(child: Text('No services available'));
    }
    return ListView.separated(
      physics: const AlwaysScrollableScrollPhysics(),
      padding: const EdgeInsets.all(24),
      itemCount: services.length,
      separatorBuilder: (context, index) => const SizedBox(height: 24),
      itemBuilder: (context, index) {
        return ServiceCard(service: services[index]);
      },
    );
  }
}
